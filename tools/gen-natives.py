"""Writes src/Script/natives.tsv: one line per event-script native,
`id<TAB>handler<TAB>name`, for the script debugger's `func` annotations.

The handlers come from the player's FFX.exe (the native tables AtelInitTotal
registers, 16-byte entries {start, poll, float result, int result}; the
handler is the int result, else the float result, else start, else poll), the
names from ffx-decomp's symbols/ffx.sym. Nothing from the game is written but
addresses and names.

usage: gen-natives.py FFX.exe ffx.sym > src/Script/natives.tsv
"""
import struct
import sys

GROUP_TABLES = [(0x0, 0x00C50050), (0x1, 0x00C52BE0), (0x4, 0x00C88D88), (0x5, 0x00C891F8),
                (0x6, 0x00C43998), (0x7, 0x00C42628), (0x8, 0x00C5DC90), (0x9, 0x00C5D8C0),
                (0xB, 0x00C40E30), (0xC, 0x00C52DD8), (0xD, 0x00C85EB0)]
# Highest index per group (Fahrenheit's call_atel.cs ranges; past them lies other data).
GROUP_MAX = {0x0: 0x267, 0x1: 0x1D, 0x4: 0x46, 0x5: 0x90, 0x6: 0x89, 0x7: 0x127,
             0x8: 0x6B, 0x9: 0x0, 0xB: 0x0F, 0xC: 0x5D, 0xD: 0x0}
TEXT = range(0x00401000, 0x00B0BC00)


def main():
    exe = open(sys.argv[1], 'rb').read()
    nt = struct.unpack_from('<I', exe, 0x3C)[0]
    count = struct.unpack_from('<H', exe, nt + 6)[0]
    table = nt + 0x18 + struct.unpack_from('<H', exe, nt + 0x14)[0]
    sections = [struct.unpack_from('<III', exe, table + i * 40 + 12) for i in range(count)]

    def u32(va):
        rva = va - 0x400000
        for start, size, raw in sections:
            if start <= rva < start + size:
                return struct.unpack_from('<I', exe, raw + rva - start)[0]
        return None

    names = {}
    for line in open(sys.argv[2], encoding='utf-8'):
        w = line.split('#', 1)[0].split()
        if len(w) >= 3 and w[1] == 'function':
            names[int(w[0], 16)] = w[2]

    print('# id\thandler\tname  (generated by tools/gen-natives.py)')
    for group, base in GROUP_TABLES:
        for index in range(GROUP_MAX[group] + 1):
            slots = [u32(base + index * 16 + 4 * k) for k in range(4)]
            slots = [s if s is not None and s in TEXT else None for s in slots]
            start, poll, fres, ires = slots
            handler = ires or fres or start or poll
            if handler is None:
                continue
            print(f'{group << 12 | index:04x}\t{handler:08x}\t{names.get(handler, "")}')


main()
