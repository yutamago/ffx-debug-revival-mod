// Writes src/Script/natives.tsv: one line per event-script native, id<TAB>handler<TAB>name, for the script
// debugger's `func` annotations. The handlers come from the player's FFX.exe: the native tables AtelInitTotal
// registers hold 16-byte entries {start, poll, float result, int result}, and the handler is the int result, else
// the float result, else start, else poll. The names come from ffx-decomp's symbols/ffx.sym. Nothing from the game
// is written but addresses and names.
//
// usage: dotnet run tools/gen-natives.cs -- <FFX.exe> <ffx.sym> [out.tsv]   (default src/Script/natives.tsv, - for stdout)

using System.Buffers.Binary;
using System.Globalization;
using System.Runtime.CompilerServices;

if (args.Length is not (2 or 3)) {
    Console.Error.WriteLine("usage: dotnet run tools/gen-natives.cs -- <FFX.exe> <ffx.sym> [out.tsv]");
    return 1;
}
string out_path = args.Length == 3 ? args[2] : Path.Combine(Path.GetDirectoryName(this_file())!, "..", "src", "Script", "natives.tsv");

(int group, uint table)[] GROUP_TABLES = [
    (0x0, 0x00c50050), (0x1, 0x00c52be0), (0x4, 0x00c88d88), (0x5, 0x00c891f8), (0x6, 0x00c43998), (0x7, 0x00c42628),
    (0x8, 0x00c5dc90), (0x9, 0x00c5d8c0), (0xb, 0x00c40e30), (0xc, 0x00c52dd8), (0xd, 0x00c85eb0),
];
// Highest index per group (Fahrenheit's call_atel.cs ranges; past them lies other data).
Dictionary<int, int> GROUP_MAX = new() {
    [0x0] = 0x267, [0x1] = 0x1d, [0x4] = 0x46, [0x5] = 0x90, [0x6] = 0x89, [0x7] = 0x127,
    [0x8] = 0x6b, [0x9] = 0x0, [0xb] = 0x0f, [0xc] = 0x5d, [0xd] = 0x0,
};
const uint TEXT_START = 0x00401000, TEXT_END = 0x00b0bc00;

byte[] exe = File.ReadAllBytes(args[0]);
int pe = BinaryPrimitives.ReadInt32LittleEndian(exe.AsSpan(0x3c));
int section_count = BinaryPrimitives.ReadUInt16LittleEndian(exe.AsSpan(pe + 6));
int section_table = pe + 0x18 + BinaryPrimitives.ReadUInt16LittleEndian(exe.AsSpan(pe + 0x14));
List<(uint start, uint size, uint raw)> sections = [];
for (int i = 0; i < section_count; i++) {
    ReadOnlySpan<byte> s = exe.AsSpan(section_table + 40 * i + 12);
    sections.Add((BinaryPrimitives.ReadUInt32LittleEndian(s), BinaryPrimitives.ReadUInt32LittleEndian(s[4..]),
                  BinaryPrimitives.ReadUInt32LittleEndian(s[8..])));
}

uint? u32(uint va) {
    uint rva = va - 0x400000;
    foreach (var (start, size, raw) in sections) {
        if (rva >= start && rva < start + size) return BinaryPrimitives.ReadUInt32LittleEndian(exe.AsSpan((int)(raw + rva - start)));
    }
    return null;
}

Dictionary<uint, string> names = [];
foreach (string line in File.ReadLines(args[1])) {
    string[] w = line.Split('#', 2)[0].Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
    if (w.Length >= 3 && w[1] == "function") names[uint.Parse(w[0].Replace("0x", ""), NumberStyles.HexNumber)] = w[2];
}

// Written by the script, not a shell redirect, so the bytes are the same in every shell and OS.
TextWriter o = new StreamWriter(out_path == "-" ? Console.OpenStandardOutput() : File.Create(out_path)) { NewLine = "\n" };
o.WriteLine("# id\thandler\tname  (generated by tools/gen-natives.cs)");
foreach (var (group, table) in GROUP_TABLES) {
    for (int index = 0; index <= GROUP_MAX[group]; index++) {
        uint?[] slots = new uint?[4];
        for (int k = 0; k < 4; k++) {
            uint? v = u32(table + (uint)(index * 16 + 4 * k));
            slots[k] = v is >= TEXT_START and < TEXT_END ? v : null;
        }
        // slots: start, poll, float result, int result
        if ((slots[3] ?? slots[2] ?? slots[0] ?? slots[1]) is not uint handler) continue;
        o.WriteLine($"{group << 12 | index:x4}\t{handler:x8}\t{names.GetValueOrDefault(handler, "")}");
    }
}
o.Dispose();
return 0;

static string this_file([CallerFilePath] string path = "") => path;
